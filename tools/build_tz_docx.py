def set_run_font(run, name="Times New Roman", size=14, bold=False, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor(0, 0, 0)
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:cs"), name)
    rFonts.set(qn("w:eastAsia"), name)


def set_paragraph_format(p, *, first_line=True, after=6, before=0, align="justify", space=1.15):
    pf = p.paragraph_format
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = space
    if align == "justify":
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    elif align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "left":
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    elif align == "right":
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pf.first_line_indent = Cm(1.25) if first_line else Cm(0)


def shade_cell(cell, hex_color="D9E2F3"):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), hex_color)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def set_cell_border(cell):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "666666")
        tcBorders.append(el)
    tcPr.append(tcBorders)


def cell_text(cell, text, *, bold=False, size=11, align="left"):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.first_line_indent = Cm(0)
    if align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "justify":
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold)
    set_cell_border(cell)
    for pp in cell.paragraphs:
        pf = pp.paragraph_format
        pf.left_indent = Cm(0.08)
        pf.right_indent = Cm(0.08)


def add_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    for i, h in enumerate(headers):
        cell_text(table.rows[0].cells[i], h, bold=True, size=11, align="center")
        shade_cell(table.rows[0].cells[i], "1F4E79")
        for p in table.rows[0].cells[i].paragraphs:
            for run in p.runs:
                run.font.color.rgb = RGBColor(255, 255, 255)
    for r_i, row in enumerate(rows):
        for c_i, val in enumerate(row):
            cell_text(table.rows[r_i + 1].cells[c_i], val, size=11)
            if r_i % 2 == 1:
                shade_cell(table.rows[r_i + 1].cells[c_i], "F2F2F2")
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return table


def heading(doc, text, level=1):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14 if level == 1 else 10)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.first_line_indent = Cm(0)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.keep_with_next = True
    run = p.add_run(text)
    set_run_font(run, size=16 if level == 1 else 14, bold=True)
    if level == 1:
        # underline via bottom border on paragraph
        pPr = p._p.get_or_add_pPr()
        pBdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "12")
        bottom.set(qn("w:space"), "4")
        bottom.set(qn("w:color"), "1F4E79")
        pBdr.append(bottom)
        pPr.append(pBdr)
    return p


def para(doc, text, *, first=True, bold=False, align="justify"):
    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=first, align=align)
    # split **bold** segments
    parts = []
    buf = text
    while "**" in buf:
        i = buf.find("**")
        j = buf.find("**", i + 2)
        if j < 0:
            break
        if i:
            parts.append((buf[:i], False))
        parts.append((buf[i + 2 : j], True))
        buf = buf[j + 2 :]
    if buf:
        parts.append((buf, False))
    if not parts:
        parts = [(text, False)]
    for t, b in parts:
        run = p.add_run(t)
        set_run_font(run, bold=bold or b)
    return p


def bullets(doc, items):
    for item in items:
        p = doc.add_paragraph()
        set_paragraph_format(p, first_line=False, after=3)
        p.paragraph_format.left_indent = Cm(1.0)
        p.paragraph_format.first_line_indent = Cm(-0.4)
        run = p.add_run("–  ")
        set_run_font(run, bold=False)
        # bold markers
        buf = item
        while "**" in buf:
            i = buf.find("**")
            j = buf.find("**", i + 2)
            if j < 0:
                break
            if i:
                r = p.add_run(buf[:i])
                set_run_font(run=r)
            r = p.add_run(buf[i + 2 : j])
            set_run_font(r, bold=True)
            buf = buf[j + 2 :]
        if buf:
            r = p.add_run(buf)
            set_run_font(r)


def numbered(doc, items):
    for n, item in enumerate(items, 1):
        p = doc.add_paragraph()
        set_paragraph_format(p, first_line=False, after=4)
        p.paragraph_format.left_indent = Cm(1.0)
        p.paragraph_format.first_line_indent = Cm(-0.75)
        run = p.add_run(f"{n}.  ")
        set_run_font(run, bold=True)
        buf = item
        while "**" in buf:
            i = buf.find("**")
            j = buf.find("**", i + 2)
            if j < 0:
                break
            if i:
                r = p.add_run(buf[:i])
                set_run_font(r)
            r = p.add_run(buf[i + 2 : j])
            set_run_font(r, bold=True)
            buf = buf[j + 2 :]
        if buf:
            r = p.add_run(buf)
            set_run_font(r)


def code_block(doc, text):
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.rows[0].cells[0]
    shade_cell(cell, "F5F5F5")
    set_cell_border(cell)
    cell.text = ""
    for i, line in enumerate(text.strip("\n").split("\n")):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.first_line_indent = Cm(0)
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        run = p.add_run(line if line else " ")
        set_run_font(run, name="Consolas", size=9)
    doc.add_paragraph()


def add_page_number(section):
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("Техническое задание  ·  SIEMED Station  ·  стр. ")
    set_run_font(run, size=9)
    # PAGE field
    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    r1 = p.add_run()
    r1._r.append(fld1)
    r2 = p.add_run()
    r2._r.append(instr)
    set_run_font(r2, size=9)
    r3 = p.add_run()
    r3._r.append(fld2)
    set_run_font(run, size=9)

    header = section.header
    header.is_linked_to_previous = False
    hp = header.paragraphs[0]
    hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    hr = hp.add_run("АНПОО «СИЭУиП»  ·  проект на согласование")
    set_run_font(hr, size=9, italic=True)


